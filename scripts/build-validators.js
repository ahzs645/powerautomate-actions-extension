#!/usr/bin/env node
/*
 * Precompile the JSON Schema validators used by the flow editor.
 *
 * Ajv normally compiles a schema at runtime with `new Function(...)`. Manifest V3
 * extension pages forbid that ('unsafe-eval' is not allowed in
 * content_security_policy.extension_pages), so `ajv.compile()` throws
 * "Refused to evaluate a string as JavaScript" inside the extension. Ajv's
 * standalone mode emits the same validation code ahead of time instead, so the
 * extension only ever runs plain, static JavaScript.
 *
 * Usage:
 *   node scripts/build-validators.js          write src/schemas/generated/*
 *   node scripts/build-validators.js --check  exit 1 if the committed output is stale
 *
 * Runs automatically before `npm run build` and `npm test` (prebuild / pretest).
 */
const fs = require('fs');
const path = require('path');
const Ajv = require('ajv').default;
const standaloneCode = require('ajv/dist/standalone').default;

const ROOT = path.resolve(__dirname, '..');
const SCHEMA_DIR = path.join(ROOT, 'src', 'schemas');
const OUT_DIR = path.join(SCHEMA_DIR, 'generated');

const HEADER =
  '/* eslint-disable */\n' +
  '// @ts-nocheck\n' +
  '// GENERATED by scripts/build-validators.js from src/schemas/workflowdefinition.json.\n' +
  '// Do not edit by hand: change the schema and run `node scripts/build-validators.js`.\n';

/** Options shared by the build and by tests that compare against a runtime-compiled validator. */
const AJV_OPTIONS = {
  allErrors: true,
  strict: false,
  // The schema uses `format: "uri"` in a couple of places; ajv-formats is not a
  // dependency and the check adds nothing for flow definitions.
  validateFormats: false,
  // Emit one function per referenced sub-schema instead of inlining it at every use;
  // the recursive action schema otherwise multiplies the generated code.
  inlineRefs: false,
  code: { source: true, esm: true, lines: true },
};

function loadWorkflowSchema() {
  const schema = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, 'workflowdefinition.json'), 'utf8'));
  // The file advertises JSON Schema draft-04, whose meta-schema Ajv 8 does not ship.
  // It uses no draft-04-only keywords, so Ajv's default (draft-07) semantics apply.
  delete schema.$schema;
  return schema;
}

function generate() {
  const ajv = new Ajv(AJV_OPTIONS);
  const validate = ajv.compile(loadWorkflowSchema());
  const code = standaloneCode(ajv, validate);
  return { 'workflowDefinitionValidator.js': HEADER + code + '\n' };
}

function main() {
  const check = process.argv.includes('--check');
  const files = generate();
  let stale = false;

  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(OUT_DIR, name);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      stale = true;
      console.error(`[build-validators] ${path.relative(ROOT, target)} is out of date.`);
    } else {
      fs.writeFileSync(target, content);
      console.log(`[build-validators] wrote ${path.relative(ROOT, target)}`);
    }
  }

  if (stale) {
    console.error('Run `node scripts/build-validators.js` and commit the result.');
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = { generate, AJV_OPTIONS, loadWorkflowSchema };
